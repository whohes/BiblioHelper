#pragma once

#include "fund_sheet.h"

#include <QString>
#include <QVector>

namespace bh::core {

// Книги из экземпляров. В файлах фонда одна строка — один экземпляр, а книга —
// это несколько строк с одинаковым названием. Программа предлагает такие группы,
// пользователь подтверждает; принадлежность к книге хранится в скрытом листе
// (столбец book_id листа «_BiblioHelper»).

// Ключ для поиска одинаковых книг: «Автор и название» без регистра, ё/е, точек,
// запятых и лишних пробелов, плюс год. «Абрамов.Ф.  Братья и сестры.» и
// «Абрамов Ф. Братья и сестры» с одним годом дают один ключ. Пусто — без названия.
QString bookKey(const FundSheet &sheet, const FundRecord &record);

// Группы из двух и более экземпляров с одинаковым ключом, которые ещё не
// собраны в одну книгу. Внутри группы — индексы записей по порядку файла;
// группы — по первой строке.
QVector<QVector<int>> suggestBookGroups(const FundSheet &sheet);

// Сколько книг в списке записей: экземпляры одной книги считаются один раз.
int countBooks(const FundSheet &sheet, const QVector<int> &records);

} // namespace bh::core
